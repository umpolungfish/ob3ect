def wh_displacement(psi, a, b):
    d = len(psi)
    omega = cmath.exp(2j * cmath.pi / d)
    tau = omega ** (a * b / 2.0)
    result = [0j] * d
    for k in range(d):
        v = psi[k] * (omega ** (b * k))
        result[(k + a) % d] = tau * v
    return result

def inner_product(u, v):
    return sum(u[k].conjugate() * v[k] for k in range(len(u)))

def norm_sq(psi):
    return inner_product(psi, psi).real

def overlap_sq(psi, a, b):
    return abs(inner_product(psi, wh_displacement(psi, a, b))) ** 2

def generate_sic_povm(psi=None):
    if psi is None: psi = D12_FIDUCIAL
    d = len(psi)
    return [wh_displacement(psi, a, b) for a in range(d) for b in range(d)]

def verify_sic(psi=None, tol=1e-12):
    if psi is None: psi = D12_FIDUCIAL
    d = len(psi)
    n = norm_sq(psi)
    target = 1.0 / (d + 1)
    max_err, fails = 0.0, 0
    for a in range(d):
        for b in range(d):
            if a == 0 and b == 0: continue
            err = abs(overlap_sq(psi, a, b) - target)
            if err > max_err: max_err = err
            if err > tol: fails += 1
    total = d*d - 1
    return {"dimension": d, "norm": n, "norm_ok": abs(n - 1.0) < tol,
            "pairs_checked": total, "pairs_passed": total - fails,
            "max_error": max_err, "equiangular_ok": fails == 0,
            "target": target, "sic_verified": abs(n - 1.0) < tol and fails == 0}

def moduli(psi=None):
    if psi is None: psi = D12_FIDUCIAL
    return [abs(z)**2 for z in psi]

def verify_moduli_sum(psi=None, tol=1e-30):
    if psi is None: psi = D12_FIDUCIAL
    s = sum(abs(z)**2 for z in psi)
    return abs(s - 1.0) < tol, s

def coordinate(k, psi=None):
    if psi is None: psi = D12_FIDUCIAL
    return psi[k]

def modulus_arm(k, psi=None):
    return abs(coordinate(k, psi))**2

def phase_arm(k, psi=None):
    z = coordinate(k, psi)
    r = abs(z)
    return 0j if r < 1e-140 else z / r

